#!/usr/bin/env node

/**
 * Generate the nginx map file for the ddwiki.reso.org server-side
 * redirector. Reads dd-output/redirects.json (produced by
 * generate-redirects.mjs) and writes an nginx-compatible map file.
 *
 * Intended for manual use only — NOT part of the dd-docs site build.
 * Run from the repo root when the redirect set changes and the nginx
 * server needs an updated map:
 *
 *   node generate-redirects.mjs   # rebuilds redirects.json
 *   node generate-nginx-map.mjs   # then rebuilds ddwiki-redirects.map
 *
 * Then drop dd-output/ddwiki-redirects.map at
 * /etc/nginx/conf.d/ddwiki-redirects.map on the redirector and reference:
 *
 *   map $request_uri $ddwiki_target {
 *     include /etc/nginx/conf.d/ddwiki-redirects.map;
 *   }
 *   if ($ddwiki_target) {
 *     return 301 https://dd.reso.org$ddwiki_target;
 *   }
 *
 * The server-side layer covers machine clients (curl, link checkers,
 * scrapers) that can't run the dd.reso.org JS handler. Browsers
 * continue to be handled by the JS handler on dd.reso.org's 404 page,
 * so this nginx layer is purely additive — sunsetting it when traffic
 * to ddwiki.reso.org drops is a single config change.
 *
 * nginx's $request_uri is byte-exact (no path normalization), so for
 * slug entries we emit both with and without a trailing slash to
 * absorb the common URL variation users may type.
 */

import { readFileSync, writeFileSync, existsSync } from 'node:fs';

const inputPath = 'dd-output/redirects.json';
const outputPath = 'dd-output/ddwiki-redirects.map';

if (!existsSync(inputPath)) {
  console.error(`${inputPath} not found. Run generate-redirects.mjs first.`);
  process.exit(1);
}

const redirects = JSON.parse(readFileSync(inputPath, 'utf-8'));

const lines = [
  '# nginx $request_uri → dd.reso.org path map.',
  '# Generated by generate-nginx-map.mjs — do not edit by hand.',
  '# Source of truth: dd-output/redirects.json (regenerate with generate-redirects.mjs).',
  '#',
  '# Use:  map $request_uri $ddwiki_target { include /etc/nginx/conf.d/ddwiki-redirects.map; }',
  '# Then: if ($ddwiki_target) { return 301 https://dd.reso.org$ddwiki_target; }',
  '',
];

let slugCount = 0;
let pageIdCount = 0;
let trailingSlashCount = 0;

for (const [key, value] of Object.entries(redirects)) {
  if (key.startsWith('pageId:')) {
    const pid = key.slice('pageId:'.length);
    lines.push(`"/pages/viewpage.action?pageId=${pid}" "${value}";`);
    pageIdCount++;
  } else {
    lines.push(`"/${key}" "${value}";`);
    slugCount++;
    if (!key.endsWith('/')) {
      lines.push(`"/${key}/" "${value}";`);
      trailingSlashCount++;
    }
  }
}

writeFileSync(outputPath, lines.join('\n') + '\n');

const sizeKb = (readFileSync(outputPath).length / 1024).toFixed(1);
console.log(`Generated ${outputPath}:`);
console.log(`  ${slugCount.toLocaleString()} slug entries`);
console.log(`  ${trailingSlashCount.toLocaleString()} trailing-slash variants`);
console.log(`  ${pageIdCount.toLocaleString()} pageId entries`);
console.log(`  ${(slugCount + trailingSlashCount + pageIdCount).toLocaleString()} total lines`);
console.log(`  ${sizeKb} KB`);
